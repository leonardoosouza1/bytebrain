def subset_weights(score, k):
    """Per candidate (last axis, n): probability that it is the lowest score of a uniformly random k-subset drawn
    without replacement, ties broken uniformly at random. Sums to 1 over the last axis."""
    n = score.shape[-1]
    assert np.isfinite(score).all() and 1 <= k <= n, (k, n)
    r = np.arange(n)
    w = np.array([math.comb(n - 1 - i, k - 1) for i in r], float) / math.comb(n, k)
    o = np.argsort(score, axis=-1, kind="stable")
    s = np.take_along_axis(score, o, -1)
    new = np.ones(s.shape, bool)                          # first position of a tie block
    new[..., 1:] = s[..., 1:] != s[..., :-1]
    last = np.ones(s.shape, bool)                         # last position of a tie block
    last[..., :-1] = new[..., 1:]
    start = np.maximum.accumulate(np.where(new, r, 0), axis=-1)
    end = np.flip(np.minimum.accumulate(np.flip(np.where(last, r, n - 1), -1), axis=-1), -1)
    cw = np.concatenate([np.zeros(s.shape[:-1] + (1,)), np.cumsum(np.broadcast_to(w, s.shape), -1)], -1)
    ws = (np.take_along_axis(cw, end + 1, -1) - np.take_along_axis(cw, start, -1)) / (end - start + 1)
    out = np.empty_like(ws)
    np.put_along_axis(out, o, ws, -1)
    return out


def brute_weights(score, k):
    n = len(score)
    w = np.zeros(n)
    subs = list(itertools.combinations(range(n), k))
    for sub in subs:
        lo = min(score[i] for i in sub)
        tied = [i for i in sub if score[i] == lo]
        for i in tied:
            w[i] += 1 / len(tied) / len(subs)
    return w


def check_subset_weights(cases=300):
    rng = np.random.default_rng(7)
    for _ in range(cases):
        n = int(rng.integers(1, 10))
        k = int(rng.integers(1, n + 1))
        s = rng.integers(0, 4, n).astype(float)
        assert np.allclose(subset_weights(s[None], k)[0], brute_weights(list(s), k), atol=1e-12), (s, k)
    assert np.allclose(subset_weights(np.zeros((3, 128)), 4), 1 / 128)
    return cases


def avg_rank(v):
    """Average rank in [0, 1) (ties share the mean rank)."""
    o = np.argsort(v, kind="stable")
    _, first, counts = np.unique(v[o], return_index=True, return_counts=True)
    r = np.empty(len(v))
    r[o] = np.repeat(first + (counts - 1) / 2, counts)
    return r / len(v)


def logit_fit(X, y, iters=50):
    """Logistic regression by Newton steps; returns coefficients, standard errors, log-likelihood."""
    X = np.column_stack([np.ones(len(y)), X])
    b = np.zeros(X.shape[1])
    for _ in range(iters):
        p = 1 / (1 + np.exp(-X @ b))
        H = X.T @ (X * (p * (1 - p))[:, None])
        b = b + np.linalg.solve(H, X.T @ (y - p))
    p = np.clip(1 / (1 + np.exp(-X @ b)), 1e-12, 1 - 1e-12)
    H = X.T @ (X * (p * (1 - p))[:, None])
    return b, np.sqrt(np.diag(np.linalg.inv(H))), float((y * np.log(p) + (1 - y) * np.log(1 - p)).sum())


def lc_score(pt, feats, y, n_seeds, n_per):
    """Cross-fitted logistic combiner (lower is picked): parse check first, then minus the linear predictor of
    P(y | feats) from a logistic fitted on the PARSING rows of the other half of the seeds (seeds 0-5 <-> 6-11).
    The cue never sees an outcome; the combiner's weights see outcomes of disjoint seeds only."""
    seed = np.repeat(np.arange(n_seeds), n_per)
    X = np.column_stack(feats)
    out, coefs = np.zeros(len(pt)), []
    for fit_on in (seed < n_seeds // 2, seed >= n_seeds // 2):
        tr = fit_on & (pt == 1)
        mu, sd = X[tr].mean(0), X[tr].std(0)
        b, _, _ = logit_fit((X[tr] - mu) / sd, y[tr])
        te = ~fit_on
        out[te] = -(np.column_stack([np.ones(int(te.sum())), (X[te] - mu) / sd]) @ b)
        coefs.append(np.round(b, 3).tolist())
    assert np.isfinite(out).all(), coefs
    return (1 - pt) * 1e6 + out, coefs


