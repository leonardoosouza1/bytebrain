def seqs_of(srcs):
    return [PRE + s.encode("utf-8", "replace") for s in srcs]


@torch.no_grad()
def off_corpus(idx, srcs, chunk=65_536):
    """Per function: share of generated bytes (after 'def ') whose 9-gram never occurs in the corpus."""
    grams, owner = [], []
    for i, b in enumerate(seqs_of(srcs)):
        for t in range(8, len(b)):                        # generated bytes from the 3rd on (8 bytes of context)
            grams.append(np.frombuffer(b[t - 8:t + 1], np.uint8))
            owner.append(i)
    owner = np.array(owner)
    cnt = np.zeros(len(grams), np.int64)
    for k in range(0, len(grams), chunk):
        g = torch.tensor(np.stack(grams[k:k + chunk]), device="cuda").long()
        lo, hi = idx.range(g, 9)
        cnt[k:k + chunk] = (hi - lo).cpu().numpy()
    off = np.zeros(len(srcs))
    n = np.bincount(owner, minlength=len(srcs))
    np.add.at(off, owner, (cnt == 0).astype(float))
    return np.where(n > 0, off / np.maximum(n, 1), 1.0), grams, cnt


@torch.no_grad()
def copy48_rows(idx, srcs, win=48):
    """Per function: (bytes whose preceding `win` bytes occur verbatim in the corpus, bytes scored), as
    mix_eval.copy_frac counts them (first `win` bytes not scored)."""
    ctxs, owner = [], []
    for i, s in enumerate(srcs):
        b = s.encode()
        for t in range(win, len(b)):
            ctxs.append(np.frombuffer(b[t - win:t], np.uint8))
            owner.append(i)
    hit = np.zeros(len(ctxs))
    for k in range(0, len(ctxs), 4096):
        c = torch.tensor(np.stack(ctxs[k:k + 4096]), device="cuda").long()
        m, _, _ = idx.next_bytes(c, lengths=(win,), cap=1)
        hit[k:k + 4096] = (m >= win).cpu().numpy()
    owner = np.array(owner, np.int64)
    return np.bincount(owner, weights=hit, minlength=len(srcs)), np.bincount(owner, minlength=len(srcs))


@torch.no_grad()
def mean_logprob(lm, srcs):
    """Mean log p(byte) at T 1 over the generated bytes (after 'def '), strided windows of lm.ctx, overlap ctx/2."""
    L, out = lm.ctx, []
    for b in seqs_of(srcs):
        x = torch.tensor(list(b), device="cuda").long()
        first = len(PRE) + 4                               # first generated byte position
        lp = torch.full((len(b),), float("nan"), device="cuda")
        start = 0
        while True:
            w = x[start:start + L]
            lg = torch.log_softmax(lm.model(w[None])[0].float(), -1)     # predicts w[1:]
            tl = lg[:-1].gather(1, w[1:, None]).squeeze(1)
            pos = torch.arange(start + 1, start + len(w), device="cuda")
            keep = pos >= (start + L // 2 if start else 0)              # each byte scored once, >= L/2 context
            lp[pos[keep]] = tl[keep]
            if start + L >= len(b):
                break
            start += L // 2
        v = lp[first:]
        assert torch.isfinite(v).all()
        out.append(float(v.mean()))
    return np.array(out)


