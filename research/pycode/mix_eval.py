"""Byte-LM + corpus index: the model proposes, the corpus counts.

Per generated byte: p = (1 - w) * p_model + w * p_index, where p_index is the next-byte distribution after the
longest context suffix (>= min_match bytes) found in the training corpus, and
  w = n / (n + kappa)                       n = occurrences behind p_index (Dirichlet backoff)
  w = 0 unless H(p_model) > tau             (--rule stress: consult the corpus only when the model is unsure)
Rules compared on the same seeds: model (w=0), always, stress. Also held-out bits/byte for each rule.
Judged by eval_samples.judge (grammar / names / runs) plus novelty (function not verbatim in the corpus).

Usage: mix_eval.py CKPT --out FILE.json [--n 128] [--bytes 600]
"""

import argparse
import json
import time

import numpy as np
import torch

from corpus_index import CorpusIndex
from eval_samples import ByteLM, CachedGen, cut_function, judge

D = "/media/llm-data/datasets/pycode"
LENGTHS = (8, 12, 16, 24, 32, 48)


def weight(rule, pm, m, h, kappa, tau):
    n = h.sum(1)
    w = torch.where(m > 0, n / (n + kappa), torch.zeros_like(n))
    if rule == "model":
        return torch.zeros_like(w)
    if rule == "stress":
        ent = -(pm * torch.log2(pm.clamp(min=1e-12))).sum(1)
        w = torch.where(ent > tau, w, torch.zeros_like(w))
    return w


@torch.no_grad()
def generate(lm, idx, rule, n, nbytes, temp, kappa, tau, seed=0):
    torch.manual_seed(seed)
    g = CachedGen(lm)
    g.reset()
    ids = torch.tensor([list(b"\n\ndef ")], device="cuda").repeat(n, 1)
    g.hist = ids.clone()
    full = ids.clone()
    logits = g._forward(ids)
    used = []
    for _ in range(nbytes):
        pm = torch.softmax(logits.float() / temp, -1)
        m, _, h = idx.next_bytes(full[:, -48:], lengths=LENGTHS, cap=512)
        w = weight(rule, pm, m, h, kappa, tau)
        pi = h / h.sum(1, keepdim=True).clamp(min=1)
        p = (1 - w[:, None]) * pm + w[:, None] * pi
        nxt = torch.multinomial(p, 1).squeeze(1)
        used.append(float((w > 0).float().mean()))
        full = torch.cat([full, nxt[:, None]], 1)
        g.hist = torch.cat([g.hist, nxt[:, None]], 1)
        if g.pos >= g.ctx:
            tail = g.hist[:, -g.keep:]
            g.reset()
            g.hist = tail
            logits = g._forward(tail)
        else:
            logits = g._forward(nxt[:, None])
    return full[:, 2:].to(torch.uint8).cpu().numpy(), float(np.mean(used))


@torch.no_grad()
def holdout_bpb(lm, idx, rule, kappa, tau, n_pos=4096):
    text = np.fromfile(f"{D}/clean_holdout.txt", dtype=np.uint8)
    r = np.random.default_rng(0)
    L = lm.ctx
    pos = r.integers(L, len(text) - 1, n_pos)
    tot = 0.0
    for s in range(0, n_pos, 256):
        ctx = torch.tensor(np.stack([text[p - L:p] for p in pos[s:s + 256]]), device="cuda").long()
        tgt = torch.tensor(text[pos[s:s + 256]].astype(np.int64), device="cuda")
        pm = torch.softmax(lm.model(ctx)[:, -1].float(), -1)
        m, _, h = idx.next_bytes(ctx[:, -48:], lengths=LENGTHS, cap=4096)
        w = weight(rule, pm, m, h, kappa, tau)
        p = (1 - w[:, None]) * pm + w[:, None] * h / h.sum(1, keepdim=True).clamp(min=1)
        tot += -torch.log2(p.gather(1, tgt[:, None]).clamp(min=1e-12)).sum().item()
    return tot / n_pos


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ckpt")
    ap.add_argument("--out", required=True)
    ap.add_argument("--n", type=int, default=128)
    ap.add_argument("--bytes", type=int, default=600)
    ap.add_argument("--temp", type=float, default=0.8)
    ap.add_argument("--kappa", type=float, default=4.0)
    ap.add_argument("--tau", type=float, default=1.0, help="model entropy (bits) above which the corpus is consulted")
    ap.add_argument("--rules", default="model,always,stress")
    ap.add_argument("--mem-frac", type=float, default=0.3)
    args = ap.parse_args()
    torch.cuda.set_per_process_memory_fraction(args.mem_frac)
    lm = ByteLM(args.ckpt)
    idx = CorpusIndex.cached(f"{D}/clean_train.txt", depth=64)
    corpus = open(f"{D}/clean_train.txt", "rb").read()
    report = {"ckpt": args.ckpt, "step": lm.step, "args": vars(args)}
    for rule in args.rules.split(","):
        t0 = time.perf_counter()
        rows, used = generate(lm, idx, rule, args.n, args.bytes, args.temp, args.kappa, args.tau)
        res = []
        for row in rows:
            src, term = cut_function(bytes(row).decode("utf-8", "replace"))
            res.append({"src": src, "terminated": term, "novel": src.encode() not in corpus, **judge(src)})
        s = {k: round(float(np.mean([r[k] for r in res])), 3)
             for k in ("terminated", "parses", "names_ok", "runs", "novel")}
        s["novel_and_parses"] = round(float(np.mean([r["novel"] and r["parses"] for r in res])), 3)
        s["corpus_used"] = round(used, 3)
        s["holdout_bpb"] = round(holdout_bpb(lm, idx, rule, args.kappa, args.tau), 3)
        s["wall_s"] = round(time.perf_counter() - t0, 1)
        report[rule] = s | {"examples": [r["src"] for r in res[:8]]}
        print(f"{rule:7s} {json.dumps(s)}", flush=True)
        with open(args.out, "w") as fh:
            json.dump(report, fh)


if __name__ == "__main__":
    main()
