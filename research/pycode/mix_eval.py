"""Byte-LM + corpus index: the model proposes, the corpus counts.

Per generated byte: p = (1 - w) * p_model + w * p_index, where p_index is the next-byte distribution after the
longest context suffix (>= min_match bytes) found in the training corpus, and
  w = n / (n + kappa)                       n = occurrences behind p_index (Dirichlet backoff)
and a gate decides whether the corpus is consulted at all:
  model   never (w = 0)
  always  every byte
  stress  only when H(p_model at the sampling temperature) > tau bits (consult when the model is unsure)
  anti    only when H <= tau (the opposite gate; same tau)
  random  i.i.d. per byte with the stress gate's in-function open rate (rate-matched control: separates
          "consult when unsure" from "consult at all"); own torch.Generator, the sampling stream is untouched
  stress24  stress and the corpus match is >= 24 bytes (smoke n=8: stress helped held-out bytes behind a long
          match and hurt those behind an 8-16 byte match; FAILED-ADAPT arm of the stress rule)
Rules are compared on the same seeds; every arm draws the same sampling noise (multinomial consumes the same
Philox draws whatever p is), so rows are paired across arms. Held-out bits/byte per rule with the same gate.
Judged by eval_samples.judge (grammar / names / runs), novelty (function not verbatim in the corpus) and copy48
(share of bytes whose 48 preceding bytes occur verbatim in the corpus).

Usage: mix_eval.py CKPT --out FILE.json [--n 128] [--bytes 800] [--seeds 0,1,2,3] [--control eval_clean.json]
"""

import argparse
import json
import random
import time

import numpy as np
import torch

from corpus_index import CorpusIndex
from eval_samples import ByteLM, CachedGen, cut_function, judge

D = "/media/llm-data/datasets/pycode"
LENGTHS = (8, 12, 16, 24, 32, 48)
RULES = ("model", "always", "stress", "anti", "random", "stress24")
PROMPT = b"\n\ndef "


def gate(rule, pg, tau, rate, rgen, m):
    """Rows where the corpus may be consulted. pg = model distribution the gate reads (sampling temperature)."""
    if rule not in RULES:
        raise ValueError(f"unknown rule {rule}")
    B = pg.shape[0]
    if rule == "model":
        return torch.zeros(B, dtype=torch.bool, device=pg.device)
    if rule == "always":
        return torch.ones(B, dtype=torch.bool, device=pg.device)
    if rule == "random":
        return torch.rand(B, device=pg.device, generator=rgen) < rate
    ent = -(pg * torch.log2(pg.clamp(min=1e-12))).sum(1)
    if rule == "stress24":
        return (ent > tau) & (m >= 24)
    return ent > tau if rule == "stress" else ent <= tau


def weight(m, h, kappa, g):
    n = h.sum(1)
    return torch.where((m > 0) & g, n / (n + kappa), torch.zeros_like(n))


@torch.no_grad()
def generate(lm, idx, rule, n, nbytes, temp, kappa, tau, rate, seed):
    torch.manual_seed(seed)
    rgen = torch.Generator(device="cuda")
    rgen.manual_seed(10_000 + seed)
    g = CachedGen(lm)
    g.reset()
    ids = torch.tensor([list(PROMPT)], device="cuda").repeat(n, 1)
    g.hist = ids.clone()
    full = ids.clone()
    logits = g._forward(ids)
    gates, ws = [], []
    for _ in range(nbytes):
        pm = torch.softmax(logits.float() / temp, -1)
        m, _, h = idx.next_bytes(full[:, -48:], lengths=LENGTHS, cap=512)
        gt = gate(rule, pm, tau, rate, rgen, m)
        w = weight(m, h, kappa, gt)
        pi = h / h.sum(1, keepdim=True).clamp(min=1)
        p = (1 - w[:, None]) * pm + w[:, None] * pi
        nxt = torch.multinomial(p, 1).squeeze(1)
        gates.append(gt.cpu())
        ws.append(w.cpu())
        full = torch.cat([full, nxt[:, None]], 1)
        g.hist = torch.cat([g.hist, nxt[:, None]], 1)
        if g.pos >= g.ctx:
            tail = g.hist[:, -g.keep:]
            g.reset()
            g.hist = tail
            logits = g._forward(tail)
        else:
            logits = g._forward(nxt[:, None])
    return full[:, len(PROMPT):].to(torch.uint8).cpu().numpy(), torch.stack(gates, 1), torch.stack(ws, 1)


@torch.no_grad()
def holdout_bpb(lm, idx, rule, kappa, tau, temp, rate, n_pos=4096):
    """Code length of held-out bytes under the mixed predictor; the mixture uses p_model at T=1 (the model's own
    prediction), the gate reads the T=temp distribution exactly as in generation."""
    text = np.fromfile(f"{D}/clean_holdout.txt", dtype=np.uint8)
    r = np.random.default_rng(0)
    L = lm.ctx
    pos = r.integers(L, len(text) - 1, n_pos)
    rgen = torch.Generator(device="cuda")
    rgen.manual_seed(20_000)
    bits, mlen, opened = [], [], []
    for s in range(0, n_pos, 256):
        ctx = torch.tensor(np.stack([text[p - L:p] for p in pos[s:s + 256]]), device="cuda").long()
        tgt = torch.tensor(text[pos[s:s + 256]].astype(np.int64), device="cuda")
        lg = lm.model(ctx)[:, -1].float()
        pm = torch.softmax(lg, -1)
        m, _, h = idx.next_bytes(ctx[:, -48:], lengths=LENGTHS, cap=4096)
        gt = gate(rule, torch.softmax(lg / temp, -1), tau, rate, rgen, m)
        w = weight(m, h, kappa, gt)
        p = (1 - w[:, None]) * pm + w[:, None] * h / h.sum(1, keepdim=True).clamp(min=1)
        bits.append(-torch.log2(p.gather(1, tgt[:, None]).clamp(min=1e-12)).squeeze(1).cpu())
        mlen.append(m.cpu())
        opened.append(gt.cpu())
    bits, mlen, opened = torch.cat(bits), torch.cat(mlen), torch.cat(opened)
    out = {"bpb": round(float(bits.mean()), 4), "gate_rate": round(float(opened.float().mean()), 4)}
    # near-duplicate split (whole functions are deduplicated by build_corpus; what remains is boilerplate and
    # near-copies across files): bpb by longest match length behind the context
    for lo, hi in ((0, 0), (8, 16), (24, 32), (48, 48)):
        sel = (mlen >= lo) & (mlen <= hi)
        out[f"m{lo}_{hi}"] = {"frac": round(float(sel.float().mean()), 4),
                              "bpb": round(float(bits[sel].mean()), 4) if sel.any() else None}
    return out, bits


@torch.no_grad()
def copy_frac(idx, srcs, win=48):
    """Share of sample bytes whose preceding `win` bytes occur verbatim in the training corpus (copying, not
    writing), and the share copied from a rare context (<= 3 occurrences: a specific file, not an idiom).
    The first `win` bytes of each function are not scored; a function shorter than `win` adds nothing."""
    ctxs = [np.frombuffer(b[t - win:t], np.uint8) for b in (s.encode() for s in srcs) for t in range(win, len(b))]
    if not ctxs:
        return 0.0, 0.0
    hit = rare = 0
    for k in range(0, len(ctxs), 4096):
        c = torch.tensor(np.stack(ctxs[k:k + 4096]), device="cuda").long()
        m, cnt, _ = idx.next_bytes(c, lengths=(win,), cap=1)
        hit += int((m >= win).sum())
        rare += int(((m >= win) & (cnt <= 3)).sum())
    return round(hit / len(ctxs), 4), round(rare / len(ctxs), 4)


def score_rows(rows, gates, ws, corpus):
    res = []
    for r, row in enumerate(rows):
        raw = bytes(row)
        try:
            raw.decode("utf-8")
            bad = False
        except UnicodeDecodeError:
            bad = True
        src, term = cut_function("def " + raw.decode("utf-8", "replace"))      # rows hold generated bytes only
        k = max(0, min(len(row), len(src.encode()) - 4))    # generated bytes inside the function
        res.append({"src": src, "terminated": term, "novel": src.encode() not in corpus, "bad_utf8": bad,
                    "fn_bytes": k, "gate_fn": int(gates[r, :k].sum()), "used_fn": int((ws[r, :k] > 0).sum()),
                    "w_sum_fn": round(float(ws[r, :k].sum()), 3), **judge(src)})
    return res


def summarize(res):
    mean = lambda f: round(float(np.mean([f(r) for r in res])), 4)  # noqa: E731
    s = {k: mean(lambda r, k=k: bool(r[k])) for k in ("terminated", "parses", "names_ok", "runs", "novel", "bad_utf8")}
    s["novel_and_parses"] = mean(lambda r: r["novel"] and r["parses"])
    s["term_parses"] = mean(lambda r: r["terminated"] and r["parses"])
    s["term_parses_novel"] = mean(lambda r: r["terminated"] and r["parses"] and r["novel"])
    nb = sum(r["fn_bytes"] for r in res)
    s["gate_fn"] = round(sum(r["gate_fn"] for r in res) / max(nb, 1), 4)
    s["used_fn"] = round(sum(r["used_fn"] for r in res) / max(nb, 1), 4)
    nu = sum(r["used_fn"] for r in res)
    s["w_mean_used"] = round(sum(r["w_sum_fn"] for r in res) / nu, 4) if nu else None
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ckpt")
    ap.add_argument("--out", required=True)
    ap.add_argument("--n", type=int, default=128)
    ap.add_argument("--bytes", type=int, default=800)
    ap.add_argument("--temp", type=float, default=0.8)
    ap.add_argument("--kappa", type=float, default=4.0)
    ap.add_argument("--tau", type=float, default=1.0, help="model entropy (bits) above which the corpus is consulted")
    ap.add_argument("--rules", default="model,always,stress,anti,random")
    ap.add_argument("--seeds", default="0")
    ap.add_argument("--rand-rate", type=float, default=None,
                    help="random gate rate; default = the stress arm's measured in-function gate rate")
    ap.add_argument("--control", default=None, help="eval_clean.json: model rule, seed 0 must reproduce its free rows")
    ap.add_argument("--mem-frac", type=float, default=0.3)
    args = ap.parse_args()
    rules = args.rules.split(",")
    for r in rules:
        if r not in RULES:
            raise SystemExit(f"unknown rule {r}")
    if "random" in rules and args.rand_rate is None:
        assert "stress" in rules and rules.index("stress") < rules.index("random"), "random needs stress first"
    seeds = [int(x) for x in args.seeds.split(",")]
    torch.cuda.set_per_process_memory_fraction(args.mem_frac)
    lm = ByteLM(args.ckpt)
    idx = CorpusIndex.cached(f"{D}/clean_train.txt", depth=64)
    corpus = open(f"{D}/clean_train.txt", "rb").read()
    report = {"ckpt": args.ckpt, "step": lm.step, "args": vars(args)}
    hold = json.load(open(f"{D}/holdout_functions.json"))
    random.Random(1).shuffle(hold)
    ref = [h["clean"] for h in hold if len(h["clean"]) <= 800][:args.n]
    report["ref_holdout_copy48"], report["ref_holdout_copy48_rare"] = copy_frac(idx, ref)
    print("reference held-out functions copy48", report["ref_holdout_copy48"], report["ref_holdout_copy48_rare"],
          flush=True)
    rate = {"gen": {}, "hold": args.rand_rate}
    bits = {}
    for rule in rules:
        t0 = time.perf_counter()
        per_seed, rows_all = {}, {}
        for seed in seeds:
            rr = args.rand_rate if args.rand_rate is not None else rate["gen"].get(seed, 0.0)
            rows, gates, ws = generate(lm, idx, rule, args.n, args.bytes, args.temp, args.kappa, args.tau, rr, seed)
            res = score_rows(rows, gates, ws, corpus)
            s = summarize(res)
            s["copy48"], s["copy48_rare"] = copy_frac(idx, [r["src"] for r in res])
            if rule == "stress":
                rate["gen"][seed] = s["gate_fn"]
            if rule == "random":
                s["rand_rate"] = rr
            per_seed[seed], rows_all[seed] = s, res
            print(f"{rule:7s} seed {seed} {json.dumps(s)}", flush=True)
        hr = rate["hold"] if rate["hold"] is not None else 0.0
        hold_s, bits[rule] = holdout_bpb(lm, idx, rule, args.kappa, args.tau, args.temp, hr)
        for other in bits:            # paired difference per held-out byte (same positions in every arm)
            if other != rule:
                dd = bits[rule] - bits[other]
                hold_s[f"d_vs_{other}"] = [round(float(dd.mean()), 4), round(float(dd.std() / len(dd) ** 0.5), 4)]
        if rule == "stress" and args.rand_rate is None:
            rate["hold"] = hold_s["gate_rate"]
        mean = {k: round(float(np.mean([per_seed[sd][k] for sd in seeds])), 4)
                for k in per_seed[seeds[0]] if isinstance(per_seed[seeds[0]][k], (int, float))}
        entry = {"mean": mean, "per_seed": per_seed, "holdout": hold_s, "rows": rows_all,
                 "wall_s": round(time.perf_counter() - t0, 1)}
        if args.control and rule == "model" and 0 in seeds:
            ctl = json.load(open(args.control))["rows"]["free"]
            mine = rows_all[0]
            same = sum(a["src"] == b["src"] for a, b in zip(ctl, mine))
            entry["control"] = {"n_ctl": len(ctl), "identical_src": same,
                                **{f"d_{k}": round(per_seed[0][k] - float(np.mean([r[k] for r in ctl])), 4)
                                   for k in ("terminated", "parses", "names_ok", "runs")}}
            print("control", json.dumps(entry["control"]), flush=True)
        report[rule] = entry
        print(f"{rule:7s} mean {json.dumps(mean)} holdout {json.dumps(hold_s)} wall {entry['wall_s']}", flush=True)
        with open(args.out, "w") as fh:
            json.dump(report, fh)


if __name__ == "__main__":
    main()
